      לכל צפייה הייתה מנפחת את המסד ומוסיפה שאלת פרטיות (מי צפה ומתי) בלי צורך.
    */
    public class VendorViewDay
    {
        public int Id { get; set; }

        public int VendorId { get; set; }

        /* היום עצמו (חצות UTC) — המפתח לצירוף לטווח תאריכים. */
        public DateTime Day { get; set; }

        public int Count { get; set; }
    }
}
