      למה זה נחוץ: עד היום נשמר מונה צפיות **אחד** (`Vendor.Views`) שרק עולה.
      ממנו אפשר לדעת "כמה צפיות בסך הכל" ואי אפשר לדעת "כמה בחודש שעבר" —
      ולכן גם לא להשוות שנה לשנה, וזו בדיוק הבקשה של בעלת המוצר.

      ⚠️ הנתון מצטבר **מרגע ההוספה בלבד**. אי אפשר לשחזר למפרע ימים שלא נספרו,
      ולכן הדוח מציג במפורש ממתי הספירה היומית קיימת — כדי שספק לא יפרש
      "0 צפיות" בתקופה ישנה כאילו לא נכנס אליו איש.

